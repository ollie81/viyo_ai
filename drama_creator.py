@router.put("/{series_id}/plot", response_model=PlotOut, dependencies=[Depends(_require_admin)])
async def update_plot(series_id: str, req: UpdatePlotRequest):
    """Free-text edits to the AI-written plot before confirming — "Do
    not permanently lock users into an incorrect story" means this
    stays open right up until the admin deliberately taps Confirm;
    nothing here checks setup_confirmed (confirming only gates the
    storyboard step itself, see confirm_setup/generate_storyboard)."""
    _require_configured()
    series = _get_series(series_id)
    plot = dict(series.get("plot_json") or {})
    patch = {k: v for k, v in req.model_dump().items() if v is not None}
    plot.update(patch)
    try:
        supabase_admin.table("series").update({"plot_json": plot}).eq("id", series_id).execute()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not save plot edits: {e}")
    return PlotOut(**{k: plot.get(k, "") for k in PlotOut.model_fields})


