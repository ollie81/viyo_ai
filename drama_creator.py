_IDEA_PROMPT = """You are the AI Drama Assistant for a vertical short-drama app — the single biggest lever a short \
drama has over a viewer is whether the first few seconds of an episode earn their attention and whether the last \
few seconds earn the next tap. You're helping a director turn a one-line idea into a complete drama concept built \
around both of those, the way the strongest working short-drama writers do it.

DIRECTOR'S IDEA: {idea_text}
GENRE: {genre}

Develop this into a complete, compelling, genre-appropriate short-drama concept — never generic, never the same \
emotional formula regardless of genre:

1. title: a short, punchy drama title (an actual title, not the idea restated).
2. plot:
   - premise: 2-3 sentences setting up the world/situation.
   - main_conflict: what's actually at stake and who's opposing whom.
   - character_motivations: what each main character wants and why, by name.
   - major_secrets: what's hidden, from whom, and why it matters once revealed.
   - emotional_turning_points: 2-3 key beats where the emotional stakes shift.
   - episode_progression: roughly how the story unfolds across episodes, and this episode's place in that arc.
   - opening_hook: the EXACT moment, line, or image episode 1 opens on — not a theme or a mood, a concrete, \
specific beat (an action already in progress, a shocking line of dialogue, a reveal, a question the viewer can't \
not need answered). No slow setup, no scene-setting before it, no logo/intro beat wasted getting to it. This is \
reused verbatim to build the episode's actual first scene — vague instructions here produce a vague opening.
   - cliffhanger: the EXACT moment episode 1 ends on — a real, specific turn (a reveal, a betrayal landing, a door \
opening on something unexpected, an ultimatum), strong enough that stopping there is genuinely uncomfortable. \
Never a vague "tension rises" — name the actual beat.
3. characters: up to {max_characters} main characters.

IF the director's idea above already names and describes specific characters (e.g. "Selam: 19, kitchen servant..."), \
use EXACTLY those characters, faithfully — same names, same ages, same roles, same relationships. Do not invent \
different people, merge any of them, or drop one, even if there are fewer than {max_characters}. Your job for a \
cast that's already written is to fill in the rich visual/voice fields below from what's given (and only invent \
specifics the idea left unstated, like an exact eye color) — never to replace a described character with your own.

IF the idea is a loose one-liner with no named cast, invent {max_characters} main characters yourself (the \
protagonist and whichever others are most central to the conflict — an antagonist, love interest, rival, or \
confidant, whichever the story actually calls for).

For each character, whichever way they came from above:
   - name, age (an approximate range, e.g. "mid-20s"), gender
   - appearance: one-sentence overall description
   - skin_tone, face_shape, eye_color, hairstyle: specific enough that an image generator stays consistent across \
multiple separate images of this character
   - body_proportions: build/height impression (e.g. "slim, average height")
   - personality: 2-3 defining traits
   - costume: ONE specific, fixed outfit this character wears consistently — exact enough to reproduce verbatim \
(e.g. "cream silk blouse, tailored black trousers, delicate gold necklace"), not a vague wardrobe guess
   - voice_description: how they'd sound speaking (tone, pace, accent impression) — guidance for voice casting, \
not an instruction to a TTS system
"""


@router.post("/{series_id}/idea", dependencies=[Depends(_require_admin)])
async def generate_idea(series_id: str, req: StartIdeaRequest):
    _require_configured()
    _get_series_owner(series_id)  # 404s if the series doesn't exist

    prompt = _IDEA_PROMPT.format(idea_text=req.idea_text, genre=req.genre or "Drama", max_characters=MAX_CHARACTERS)
    _check_daily_cap(_estimate_openai_text_cost_cents(prompt))
    try:
        response = _openai_client.responses.parse(
            model=OPENAI_TEXT_MODEL,
            input=[{"role": "user", "content": prompt}],
            text_format=DramaIdeaSchema,
        )
    except Exception as e:
        raise HTTPException(status_code=502, detail=f"Drama idea generation failed: {e}")

    parsed = response.output_parsed
    if parsed is None or not parsed.characters:
        raise HTTPException(status_code=502, detail="GPT returned a response Drama Creator couldn't parse.")

    cost_cents = _openai_text_cost_cents(response.usage)
    _log_cost(series_id, "drama_idea", cost_cents, provider="openai")

    drafts = parsed.characters[:MAX_CHARACTERS]
    save_req = SaveCastRequest(
        characters=[
            CharacterSaveIn(
                name=c.name,
                age=c.age,
                gender=c.gender,
                appearance=c.appearance,
                clothing=c.costume,
                costume_lock=c.costume,
                personality=c.personality,
                skin_tone=c.skin_tone,
                face_shape=c.face_shape,
                eye_color=c.eye_color,
                hairstyle=c.hairstyle,
                body_proportions=c.body_proportions,
                voice_description=c.voice_description,
            )
            for c in drafts
        ],
        locations=[],
    )
    # Reuses save_cast's own real upsert (studio.py) rather than a
    # fresh insert here — this series has no characters yet (brand new
    # drama), so every item has no `id` and this is a plain insert
    # under the hood, but going through save_cast means the exact same
    # id-stability guarantees apply the moment the admin edits anything
    # afterward, from either this flow or the old one.
    cast = await save_cast(series_id, save_req)

    plot_dict = parsed.plot.model_dump()
    try:
        supabase_admin.table("series").update({
            "title": parsed.title,
            "plot_json": plot_dict,
            # The director's own words, verbatim — fed back into cover
            # and storyboard generation below (see generate_cover/
            # generate_storyboard) so style/format direction the idea
            # carried (shot style, location limits, cultural/costume
            # accuracy notes, pacing) survives past this first step
            # instead of only surviving whatever the structured plot
            # fields happened to capture.
            "story_notes": req.idea_text,
        }).eq("id", series_id).execute()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not save the generated story: {e}")

    return {
        "series_id": series_id,
        "title": parsed.title,
        "plot": PlotOut(**plot_dict),
        "characters": cast.characters,
        "cost_usd_cents": cost_cents,
        "points_used": _points_used(series_id),
    }


