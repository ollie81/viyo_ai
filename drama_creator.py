@router.post("/{series_id}/cover", response_model=CoverResponse, dependencies=[Depends(_require_admin)])
async def generate_cover(series_id: str):
    """Regeneratable at any time, confirmed or not — "Allow the user to
    regenerate the cover" per the spec, not a one-shot."""
    _require_configured()
    series = _get_series(series_id)
    characters = _load_characters(series_id)
    portrait_urls = [c["portrait_url"] for c in characters if c.get("portrait_url")]
    if not portrait_urls:
        raise HTTPException(
            status_code=400,
            detail="Generate at least one character portrait first — the cover is built to match the approved cast, not invented.",
        )
    plot = series.get("plot_json") or {}
    prompt = _COVER_PROMPT.format(
        genre=series.get("genre") or "Drama",
        premise=plot.get("premise") or series.get("description") or "",
        main_conflict=plot.get("main_conflict") or "",
        story_notes=series.get("story_notes") or "none given",
    )
    result = _generate_and_upload_image_with_references(
        prompt, portrait_urls, f"drama-covers/{series_id}", "drama_cover", series_id=series_id
    )
    try:
        supabase_admin.table("series").update({"cover_image_url": result.image_url}).eq("id", series_id).execute()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not save the generated cover: {e}")
    return CoverResponse(cover_image_url=result.image_url, cost_usd_cents=result.cost_usd_cents, points_used=_points_used(series_id))


