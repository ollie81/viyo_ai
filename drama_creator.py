def _require_configured() -> None:
    if supabase_admin is None:
        raise HTTPException(status_code=503, detail="Drama Creator is not configured (Supabase).")
    if _gemini_client is None:
        raise HTTPException(status_code=503, detail="Drama Creator is not configured (GEMINI_API_KEY unset) — needed for cover/reference-sheet images.")
    if _openai_client is None:
        raise HTTPException(status_code=503, detail="Drama Creator is not configured (OPENAI_API_KEY unset) — needed for story/storyboard writing.")


def _get_series(series_id: str) -> dict:
    try:
        rows = supabase_admin.table("series").select("*").eq("id", series_id).limit(1).execute().data
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Could not load drama: {e}")
    if not rows:
        raise HTTPException(status_code=404, detail="Drama not found.")
    return rows[0]


def _points_used(series_id: str) -> int:
    """Real spend so far on this drama, read back from the same
    studio_api_costs log every Gemini call in this file writes to via
    _log_cost — "points" is just this app's display label for it
    (1 point = 1 cent), never an invented number."""
    try:
        rows = (
            supabase_admin.table("studio_api_costs").select("cost_usd_cents").eq("series_id", series_id).execute().data
        ) or []
    except Exception:
        return 0
    return sum(int(r.get("cost_usd_cents") or 0) for r in rows)


