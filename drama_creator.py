"""
Viyo AI Drama Creator: the "New Drama" AI-assistant flow — turn a one-
line story idea into a complete, structured drama (title, plot,
characters) the way an actual drama writer would, then a cinematic
cover, a four-view reference sheet per character, and finally an
AI-written episode-1 storyboard, all without ever requiring a
pre-written script.

This is a NEW entry point alongside Viyo Studio's existing "paste a
script" flow (studio.py) — it does not replace it. Both write into the
exact same tables (`series`, `series_characters`, `series_scenes`,
`series_scene_lines`) and the exact same downstream screens (Voices,
Scenes, Publish) keep working completely unmodified regardless of
which flow produced the cast/scenes they're looking at. Concretely
reused rather than reimplemented from studio.py: the cost-cap
machinery (provider-agnostic — see `_log_cost`'s own `provider` param),
`_get_character`/`_load_characters`,
`CharacterIn`/`CharacterSaveIn`/`SaveCastRequest`/`save_cast` (the real
upsert that keeps character ids stable), `SceneOut`/`SceneSplitResult`/
`ScenesResponse`/`_persist_episode_scenes` (so an AI-written storyboard
is saved in the exact same shape `split_scenes` already produces), and
the new (added alongside this file)
`_generate_and_upload_image_with_references` for reference-conditioned
image generation.

Two different model providers, deliberately: the actual story/
storyboard WRITING (idea -> plot+cast, and the episode storyboard) runs
on GPT (OpenAI, see the client/constants just below) — picked
specifically for narrative/hook quality at the user's own request — while
every IMAGE generation (portraits via studio.py's existing endpoint,
covers, four-view sheets) stays on Gemini, since that's where the
reference-image-conditioning consistency machinery lives. Nothing
about image generation changed in this pass.

Admin-only, same `X-Admin-Key` gate as every other Studio surface —
Viyo Studio has no per-user role concept (see studio.py's own
docstring on why), and this is an extension of Studio, not a new
consumer feature.

Honesty notes (per this feature's own spec — do not silently overstate
what's actually wired up):
- The four-view sheet's three additional views are generated by
  conditioning Gemini's image model on the approved portrait (the
  strongest consistency mechanism this provider actually exposes for
  "make this look like that"). That is NOT a hard guarantee of pixel-
  identical consistency across all four views — a generative model can
  still drift. Nothing here claims otherwise; the admin can regenerate
  a view and is expected to actually look at the composed sheet before
  confirming, same as every other generated asset in Studio.
- `drama_aspect_ratio` is captured on the series row and validated,
  but actual episode RENDERING (assemble_episode in studio.py) is
  still 9:16-only end to end — update_episode_settings below rejects
  anything else rather than silently accepting a setting nothing
  downstream honors.
- `episode_duration_seconds` genuinely drives how many scenes the AI
  storyboard writes (via ads_studio.py's `_scene_count_for_duration`),
  but the exact final assembled runtime still depends on how long each
  scene's dialogue/Veo clip actually comes out, same as every other
  Studio/Ads Studio episode.

New columns this file depends on (`series.plot_json`,
`series.setup_confirmed`, `series.setup_confirmed_at`,
`series.episode_duration_seconds`, `series.drama_aspect_ratio`, and
ten additive `series_characters` columns) are NOT created by this
codebase — handed over separately as drama_creator_schema.sql, same
"no migration-runner access" constraint as every other table here.
"""
