# AI-written storyboard (replaces "paste a script" for episode 1)
# ---------------------------------------------------------------------------
_STORYBOARD_PROMPT = """You are a director planning episode {episode_number} of a vertical short-drama into \
individual scenes, built directly from this story's plot and cast — write exactly {scene_count} scenes totaling \
roughly {duration} seconds of screen time, pacing that length into genuinely different beats, not padding.

TITLE: {title}
GENRE: {genre}
PREMISE: {premise}
MAIN CONFLICT: {main_conflict}
EMOTIONAL TURNING POINTS: {turning_points}
OPENING HOOK (scene 1 must BE this, not lead up to it): {opening_hook}
CLIFFHANGER (the final scene must end ON this, not merely gesture toward it): {cliffhanger}
DIRECTOR'S OWN NOTES (follow any format/style/location constraints here exactly — e.g. a location cap, a shot-\
style preference, setting/cultural detail): {story_notes}

CAST:
{cast_block}

For each scene, identify:
- location: a short location name
- camera_shot: one of "wide", "medium", "close-up" — pick whichever best suits the scene's emotional beat
- characters_present: every character who appears, by their exact name above
- visual_description: what's visible on screen — setting, who's where, their physical actions, their facial \
expressions, and any notable camera movement (e.g. "slow push in", "handheld, following") — specific enough to \
generate an accurate scene image from
- lines: the dialogue for this scene, in order, each with the speaking character's exact name and their line \
(a pure visual beat can have zero lines)

Scene 1 is the single most important scene in the episode: it must open on the OPENING HOOK above, already \
happening — no logo beat, no character introduction, no establishing shot before it, nothing that delays it by \
even one beat. If a viewer only watched the first 2 seconds, those 2 seconds must already be the hook.

The final scene is the second most important: it must land ON the CLIFFHANGER above as a real, felt turn — not a \
fade-out, not a vague "to be continued" feeling, an actual moment that makes NOT tapping the next episode feel \
wrong. Every scene in between earns that ending; none of them pad toward it.

Keep dialogue natural and specific to these characters, never a generic summary read aloud.
"""


class StoryboardRequest(BaseModel):
    episode_number: int = 1


@router.post("/{series_id}/storyboard", response_model=ScenesResponse, dependencies=[Depends(_require_admin)])
async def generate_storyboard(series_id: str, req: StoryboardRequest):
    _require_configured()
    series = _get_series(series_id)
    if not series.get("setup_confirmed"):
        raise HTTPException(status_code=400, detail="Confirm the story setup before generating the storyboard.")

    plot = series.get("plot_json") or {}
    characters = _load_characters(series_id)
    if not characters:
        raise HTTPException(status_code=400, detail="No characters to build scenes around.")

    duration = int(series.get("episode_duration_seconds") or 30)
    # An explicit override (set via /episode-settings) always wins over
    # the default duration->count curve — that curve was built for ad
    # pacing (ads_studio.py's _scene_count_for_duration: a few longer
    # scenes) and under-produces for a drama scripted as many short,
    # tight beats, e.g. 10-12 close-up scenes in a 35-45s episode.
    scene_count = series.get("episode_scene_count") or _scene_count_for_duration(duration)
    cast_block = "\n".join(
        f"- {c.get('name')}: {c.get('appearance') or ''} Personality: {c.get('personality') or ''}"
        for c in characters
    )
    prompt = _STORYBOARD_PROMPT.format(
        episode_number=req.episode_number,
        scene_count=scene_count,
        duration=duration,
        title=series.get("title") or "",
        genre=series.get("genre") or "Drama",
        premise=plot.get("premise") or "",
        main_conflict=plot.get("main_conflict") or "",
        turning_points=plot.get("emotional_turning_points") or "",
        story_notes=series.get("story_notes") or "none given",
        opening_hook=plot.get("opening_hook") or "",
        cliffhanger=plot.get("cliffhanger") or "",
        cast_block=cast_block,
    )
    _check_daily_cap(_estimate_openai_text_cost_cents(prompt))
    try:
        response = _openai_client.responses.parse(
            model=OPENAI_TEXT_MODEL,
            input=[{"role": "user", "content": prompt}],
            text_format=SceneSplitResult,
        )
    except Exception as e:
        raise HTTPException(status_code=502, detail=f"Storyboard generation failed: {e}")

    parsed = response.output_parsed
    if parsed is None or not parsed.scenes:
        raise HTTPException(status_code=502, detail="GPT returned a response Drama Creator couldn't parse.")

    cost_cents = _openai_text_cost_cents(response.usage)
    _log_cost(series_id, "drama_storyboard", cost_cents, provider="openai")

    # Same replace-all persistence split_scenes uses — produces the
    # identical series_scenes/series_scene_lines shape, so the existing
    # Scenes screen (and every per-scene image/video/audio endpoint)
    # works on these scenes completely unmodified.
    saved_scenes = _persist_episode_scenes(series_id, req.episode_number, parsed.scenes)
    return ScenesResponse(scenes=saved_scenes, cost_usd_cents=cost_cents)
